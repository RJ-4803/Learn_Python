x="10" # assigning string value to variable x

print(x)        # Output: 10
print(type(x))  # Output: <class 'str'>


print(int(x))   # typecasting from string to integer
print(type(int(x)))  # Output: <class 'int'>

print(float(x)) # typecasting from string to float
print(type(float(x)))  # Output: <class 'float'>